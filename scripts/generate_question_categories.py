FALLBACKS = {
    "大学心理学": "心理学基础与研究方法",
    "教师伦理学": "伦理学基础与价值理论",
    "高等教育学": "高等教育理念历史与发展",
    "高等教育法规": "法理基础与教育法体系",
}


def classify(bank: str, q: dict) -> str:
    if q.get("kind") == "multi" and len(q.get("options", {})) > 0 and len(q.get("answer", "")) == len(q.get("options", {})):
        return "多选全选题"

    text = " ".join(
        [
            q.get("type", ""),
            q.get("stem", ""),
            " ".join(str(v) for v in q.get("options", {}).values()),
        ]
    )
    scores: Counter[str] = Counter()
    for category, keywords in RULES[bank]:
        for kw in keywords:
            if kw in text:
                scores[category] += len(kw) + 2 * text.count(kw)

    if bank == "大学心理学" and "大学生" in text and any(w in text for w in ("心理", "发展", "自我", "适应")):
        scores["大学生发展与自我意识"] += 8
    if bank == "教师伦理学" and "教师" in text and "学生" in text:
        scores["教书育人与师生伦理"] += 8
    if bank == "高等教育学" and "教学" in text and "课程" not in text:
        scores["教学过程方法与课堂组织"] += 5
    if bank == "高等教育法规" and "行政" in text:
        scores["行政许可监督与法律救济"] += 5

    if scores:
        return scores.most_common(1)[0][0]
    return FALLBACKS[bank]


def read_questions(path: Path) -> list[dict]:
    df = pd.read_excel(path, sheet_name=0, header=None)
    questions = []
    for _, row in df.iterrows():
        q = parse_cell_to_question(row.iloc[0], row.iloc[1])
        if _question_ok(q):
            questions.append(q)
    return questions


def main() -> None:
    archive: dict[str, dict[str, str]] = {}
    summary: dict[str, dict[str, int]] = {}
    for path in sorted(ROOT.glob("*.xlsx")):
        subject = path.stem.removesuffix("2026").replace("高等教育法规与政策", "高等教育法规")
        if subject not in RULES:
            continue
        bank_map: dict[str, str] = {}
        counts: Counter[str] = Counter()
        for q in read_questions(path):
            category = classify(subject, q)
            bank_map[str(q["id"])] = category
            counts[category] += 1
        archive[path.stem] = dict(sorted(bank_map.items()))
        summary[path.stem] = dict(counts.most_common())

    out = ROOT / "question_categories.json"
    out.write_text(json.dumps(archive, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
